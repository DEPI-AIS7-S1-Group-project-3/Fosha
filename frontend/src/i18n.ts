export function translateNote(note: string | undefined | null, lang: Language): string {
  if (!note) return '';
  if (lang !== 'ar') return note;
  return AR_NOTES[note] || note;
}

export function formatNumber(n: number | string, lang: Language): string {
  if (lang !== 'ar') return String(n);
  const arabicDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return String(n).replace(/\d/g, (d) => arabicDigits[Number(d)]);
}

export function translate(key: keyof typeof I18N.en, lang: Language, params?: Record<string, string | number>): string {
  let val = (I18N[lang] as Record<string, any>)[key] || I18N.en[key] || '';
  if (typeof val !== 'string') return '';
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      val = val.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return val;
}
